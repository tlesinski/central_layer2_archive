CREATE TABLE TBL_ARCHIVER_AUDIT_RESULTS
(
  AUDIT_RESULT_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  RUN_ID                      NUMBER NOT NULL,
  SOURCE_DB_LINK              VARCHAR2(128) NOT NULL,
  SOURCE_OWNER                VARCHAR2(128) NOT NULL,
  SOURCE_TABLE_NAME           VARCHAR2(128) NOT NULL,
  TARGET_OWNER                VARCHAR2(128) NOT NULL,
  TARGET_TABLE_NAME           VARCHAR2(128) NOT NULL,
  ARCHIVE_UNIT_TYPE           VARCHAR2(20) NOT NULL,
  PARTITION_HIGH_VALUE        VARCHAR2(4000) NOT NULL,
  SUBPARTITION_HIGH_VALUE     VARCHAR2(4000) DEFAULT '#' NOT NULL,
  PREV_PARTITION_HIGH_VALUE   VARCHAR2(4000),
  SOURCE_PARTITION_NAME       VARCHAR2(128),
  SOURCE_SUBPARTITION_NAME    VARCHAR2(128),
  TARGET_PARTITION_NAME       VARCHAR2(128),
  TARGET_SUBPARTITION_NAME    VARCHAR2(128),
  STORED_SOURCE_ROW_COUNT     NUMBER,
  STORED_TARGET_ROW_COUNT     NUMBER,
  FRESH_SOURCE_ROW_COUNT      NUMBER,
  FRESH_TARGET_ROW_COUNT      NUMBER,
  COUNT_DIFFERENCE            NUMBER,
  AUDIT_STATUS                VARCHAR2(20) NOT NULL,
  ERROR_MESSAGE               VARCHAR2(4000),
  CHECKED_AT                  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT TBL_ARCHIVER_AUDIT_RESULTS_PK PRIMARY KEY (AUDIT_RESULT_ID),
  CONSTRAINT TBL_ARCHIVER_AUDIT_RESULTS_FK1 FOREIGN KEY (RUN_ID)
    REFERENCES TBL_ARCHIVER_RUNS (RUN_ID),
  CONSTRAINT TBL_ARCHIVER_AUDIT_RESULTS_CK1 CHECK
    (ARCHIVE_UNIT_TYPE IN ('PARTITION', 'SUBPARTITION')),
  CONSTRAINT TBL_ARCHIVER_AUDIT_RESULTS_CK2 CHECK
    (AUDIT_STATUS IN ('MATCH', 'MISMATCH', 'ERROR'))
);

CREATE INDEX TBL_ARCHIVER_AUDIT_RESULTS_IDX1
  ON TBL_ARCHIVER_AUDIT_RESULTS (RUN_ID, AUDIT_STATUS);

CREATE INDEX TBL_ARCHIVER_AUDIT_RESULTS_IDX2
  ON TBL_ARCHIVER_AUDIT_RESULTS
  (SOURCE_DB_LINK, SOURCE_OWNER, SOURCE_TABLE_NAME);
